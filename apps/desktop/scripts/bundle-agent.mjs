import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { chmod, copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const desktop = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const binaries = resolve(desktop, "src-tauri/binaries");
const work = resolve(binaries, "build");
const bundle = resolve(work, "sync-agent.cjs");
const blob = resolve(work, "sync-agent.blob");
const seaConfig = resolve(work, "sea-config.json");
const stamp = resolve(work, "sync-agent.sha256");

const triple = /^host: (\S+)$/m.exec(execFileSync("rustc", ["-vV"], { encoding: "utf8" }))?.[1];
if (!triple) throw new Error("could not read the Rust host target triple from `rustc -vV`");
const windows = process.platform === "win32";
const mac = process.platform === "darwin";
const binary = resolve(binaries, `nautilus-sync-agent-${triple}${windows ? ".exe" : ""}`);

await mkdir(work, { recursive: true });
await build({
  entryPoints: [resolve(desktop, "../sync-agent/src/cli.ts")],
  outfile: bundle,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node24",
  banner: {
    js: "// Generated by apps/desktop/scripts/bundle-agent.mjs. Do not edit.",
  },
  logLevel: "warning",
});

const hash = createHash("sha256")
  .update(process.version)
  .update(await readFile(bundle))
  .digest("hex");
const built = await readFile(stamp, "utf8").catch(() => null);
const exists = await readFile(binary).then(
  () => true,
  () => false,
);
if (built === hash && exists) {
  console.log(`sync agent binary is up to date: ${binary}`);
  process.exit(0);
}

await writeFile(
  seaConfig,
  JSON.stringify({
    main: bundle,
    output: blob,
    disableExperimentalSEAWarning: true,
    useCodeCache: false,
  }),
);
execFileSync(process.execPath, ["--experimental-sea-config", seaConfig], {
  stdio: "inherit",
});

await rm(binary, { force: true });
await copyFile(process.execPath, binary);
await chmod(binary, 0o755);
if (mac)
  execFileSync("codesign", ["--remove-signature", binary], {
    stdio: "inherit",
  });
const postject = resolve(desktop, "node_modules/.bin", windows ? "postject.cmd" : "postject");
execFileSync(
  postject,
  [
    binary,
    "NODE_SEA_BLOB",
    blob,
    "--sentinel-fuse",
    "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2",
    ...(mac ? ["--macho-segment-name", "NODE_SEA"] : []),
  ],
  { stdio: "inherit", shell: windows },
);
if (mac) execFileSync("codesign", ["--sign", "-", binary], { stdio: "inherit" });

await writeFile(stamp, hash);
console.log(`built sync agent binary ${binary}`);
